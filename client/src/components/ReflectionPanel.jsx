import { useState } from 'react';
import { api } from '../api.js';

/**
 * ReflectionPanel: requests an AI weekly reflection from the backend.
 * The backend decides which provider answers (mock by default, Gemini if
 * configured) — the UI is provider-agnostic.
 */
export default function ReflectionPanel() {
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const run = async () => {
    setLoading(true);
    setError('');
    try {
      setResult(await api.reflect());
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="card ai-panel">
      <p className="muted">
        Let AI read your trackers, entries, and goals from the last 7 days and write a short
        reflection with highlights and suggested next steps.
      </p>
      <button onClick={run} disabled={loading}>
        {loading ? 'Thinking…' : '✨ Generate weekly reflection'}
      </button>
      {error && <div className="error">{error}</div>}

      {result && (
        <div style={{ marginTop: 16 }}>
          <p>{result.summary}</p>

          {result.highlights?.length > 0 && (
            <>
              <strong>Highlights</strong>
              <ul>
                {result.highlights.map((h, i) => (
                  <li key={i}>{h}</li>
                ))}
              </ul>
            </>
          )}

          {result.suggestions?.length > 0 && (
            <>
              <strong>Suggestions</strong>
              <ul>
                {result.suggestions.map((s, i) => (
                  <li key={i}>{s}</li>
                ))}
              </ul>
            </>
          )}

          <div className="ai-provider">Generated by: {result.provider}</div>
        </div>
      )}
    </div>
  );
}
